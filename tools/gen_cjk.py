#!/usr/bin/env python3
"""Renders the game's Chinese characters into 12x12 1-bit glyphs (main/cjk.c).
Font: Noto Sans CJK (SIL OFL). Only the characters listed below are stored.
Needs Pillow (pip install pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

CHARS = ("摩天大廈"                      # title
         "堂空層樓梯防火過山泳池溜冰中庭宴會攀石花園電視台升降機寫字住宅茶餐廳單人房務部保安室雙套酒戲院診所回收站停車場高速地鐵禮"
         "泵房通風溫泉化石館寶夜市水族實驗地熱心庫")   # underground challenge   # menu names only: no shop / signboard text
SEEN = []
for ch in CHARS:
    if ch not in SEEN:
        SEEN.append(ch)
FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"
def render(size, dy, thr):
    font = ImageFont.truetype(FONT, size, index=3)   # HK shapes in this collection
    out = []
    for ch in sorted(SEEN):
        im = Image.new("L", (size, size), 0)
        ImageDraw.Draw(im).text((0, dy), ch, fill=255, font=font)
        bits = []
        for y in range(size):
            v = 0
            for x in range(size):
                if im.getpixel((x, y)) >= thr:
                    v |= 1 << (15 - x)
            bits.append(v)
        out.append((ord(ch), ch, bits))
    return out
rows = render(12, -2, 110)
out = ["/* Generated by tools/gen_cjk.py from Noto Sans CJK (SIL OFL). Do not edit. */",
       '#include "cjk.h"', "", f"const int g_cjk_n = {len(rows)};",
       "const uint16_t g_cjk_cp[] = {" + ", ".join(f"0x{c:04x}" for c, _, _ in rows) + "};",
       "const uint16_t g_cjk_bits[][12] = {"]
for c, ch, bits in rows:
    out.append("    {" + ", ".join(f"0x{b:04x}" for b in bits) + f"}},  /* {ch} */")
out.append("};")
Path(__file__).resolve().parent.parent.joinpath("main/cjk.c").write_text("\n".join(out) + "\n")
print(len(rows), "glyphs at 12 px,", len(rows) * 26, "bytes of flash")
